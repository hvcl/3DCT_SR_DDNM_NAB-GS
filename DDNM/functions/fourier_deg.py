class GrayChannelOperator(A_functions):
    """
    Adapter for operators that only work on a single channel.
    Assumes input images are grayscale replicated across channels and maps them
    through a 1-channel base operator, then broadcasts outputs back to all channels.
    """

    def __init__(self, base_operator, channels, img_dim, device):
        super().__init__()
        self.base = base_operator
        self.channels = int(channels)
        self.img_dim = int(img_dim)
        self.device = torch.device(device)

    def _to_image(self, x):
        if x.dim() == 4:
            return x
        if x.dim() == 2:
            return x.view(x.shape[0], self.channels, self.img_dim, self.img_dim)
        raise ValueError(f"Unexpected tensor shape: {x.shape}")

    def _first_channel_flat(self, x):
        x_img = self._to_image(x)
        return x_img[:, 0:1].reshape(x_img.shape[0], -1)

    def prepare_measurement(self, y):
        if y.dim() == 4:
            return y[:, 0:1].reshape(y.shape[0], -1)
        if y.dim() == 2 and y.shape[1] == self.channels * self.img_dim * self.img_dim:
            return self._first_channel_flat(y)
        return y

    def _repeat_channels(self, flat):
        if flat.dim() == 4:
            img = flat
        else:
            img = flat.view(flat.shape[0], 1, self.img_dim, self.img_dim)
        return img.repeat(1, self.channels, 1, 1).reshape(img.shape[0], -1)

    def V(self, vec):
        out = self.base.V(self._first_channel_flat(vec))
        return self._repeat_channels(out)

    def Vt(self, vec):
        out = self.base.Vt(self._first_channel_flat(vec))
        return self._repeat_channels(out)

    def U(self, vec):
        out = self.base.U(vec)
        return self._repeat_channels(out)

    def Ut(self, vec):
        out = self.base.Ut(self._first_channel_flat(vec))
        return self._repeat_channels(out)

    def singulars(self):
        return self.base.singulars()

    def add_zeros(self, vec):
        return self.base.add_zeros(vec)

    def A(self, x):
        return self.base.A(self._first_channel_flat(x))

    def A_pinv(self, y):
        out = self.base.A_pinv(self.prepare_measurement(y))
        return self._repeat_channels(out)

    def At(self, y):
        out = self.base.At(self.prepare_measurement(y))
        return self._repeat_channels(out)

    def Lambda(self, vec, a, sigma_y, sigma_t, eta):
        out = self.base.Lambda(vec, a, sigma_y, sigma_t, eta)
        return self._repeat_channels(out)

    def Lambda_noise(self, vec, a, sigma_y, sigma_t, eta, epsilon):
        out = self.base.Lambda_noise(vec, a, sigma_y, sigma_t, eta, epsilon)
        return self._repeat_channels(out)
